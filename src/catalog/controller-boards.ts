function createPins(input: {
  readonly indices: readonly number[];
  readonly mcu: readonly string[];
  readonly labels?: readonly string[];
}) {
  return input.indices.map((index, offset) => ({
    index,
    label: input.labels?.[offset] ?? `D${index}`,
    mcu: input.mcu[offset] ?? '',
  }));
}

